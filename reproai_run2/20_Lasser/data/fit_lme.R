library(lme4)
library(lmerTest)
tweets_NG <- read.csv("C:/Users/lroesele.IVV5NET/AppData/Local/Temp/opencode/reprochecks/reproai_run2/20_Lasser/data/tweets_for_lme_modelling_NG.csv", colClasses=c("author_id"="character"))
tweets_NG$party <- factor(tweets_NG$party)
cat("rows:", nrow(tweets_NG), " authors:", length(unique(tweets_NG$author_id)), "\n")
model_NG <- lmer(NG ~ 1 + belief * truth + belief * truth * party + (1 + belief * truth|author_id), data=tweets_NG, control=lmerControl(optCtrl=list(maxfun=30000),optimizer="bobyqa" ))
s <- summary(model_NG)
print(s$coefficients)
cat("N obs:", nobs(model_NG), "\n")
